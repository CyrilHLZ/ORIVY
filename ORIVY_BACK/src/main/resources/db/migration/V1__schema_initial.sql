-- ---------- Membres ----------
CREATE TABLE utilisateur (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom                VARCHAR(255),
    prenom             VARCHAR(255),
    date_de_naissance  DATE,
    email              VARCHAR(255) CONSTRAINT uk_utilisateur_email UNIQUE,
    mot_de_passe       VARCHAR(255),          -- empreinte BCrypt, jamais le mot de passe en clair
    bio                VARCHAR(500),
    role               VARCHAR(255),          -- "utilisateur" ou "admin"
    numero_telephone   VARCHAR(255),
    adresse            VARCHAR(255),
    ville              VARCHAR(255),
    code_postal        VARCHAR(255),
    pays               VARCHAR(255),
    photo_url          VARCHAR(255)
);

-- ---------- Lieux de la carte ----------
CREATE TABLE point_interet (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom            VARCHAR(255)     NOT NULL,
    type           VARCHAR(255)     NOT NULL,   -- la catégorie : parc, culture, monument…
    description    VARCHAR(255),
    adresse        VARCHAR(255),
    latitude       DOUBLE PRECISION NOT NULL,
    longitude      DOUBLE PRECISION NOT NULL,
    couleur        VARCHAR(255),
    image_url      TEXT,
    image_source   TEXT,
    image_licence  TEXT
);

CREATE TABLE activite_carte (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom          VARCHAR(255)                NOT NULL,
    categorie    VARCHAR(255)                NOT NULL,
    description  VARCHAR(255),
    date_debut   TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    lieu         VARCHAR(255),
    latitude     DOUBLE PRECISION,
    longitude    DOUBLE PRECISION,
    image_url    VARCHAR(255)
);

CREATE TABLE promenade (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom            VARCHAR(255) NOT NULL,
    description    VARCHAR(255),
    difficulte     VARCHAR(255),
    distance_km    DOUBLE PRECISION,
    duree_minutes  INTEGER,
    parcours_json  VARCHAR(10000)               -- le tracé, en GeoJSON
);

-- ---------- Sorties ----------
CREATE TABLE sortie (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nom              VARCHAR(255)                   NOT NULL,
    description      VARCHAR(600),
    categorie        VARCHAR(255),
    date_debut       TIMESTAMP(6) WITHOUT TIME ZONE NOT NULL,
    lieu             VARCHAR(255)                   NOT NULL,
    latitude         DOUBLE PRECISION,
    longitude        DOUBLE PRECISION,
    nombre_max       INTEGER CONSTRAINT ck_sortie_nombre_max CHECK (nombre_max >= 2),   -- NULL = places illimitées
    image_url        VARCHAR(255),
    organisateur_id  BIGINT CONSTRAINT fk_sortie_organisateur REFERENCES utilisateur (id)
);

CREATE TABLE sortie_participant (
    sortie_id       BIGINT NOT NULL CONSTRAINT fk_participant_sortie REFERENCES sortie (id),
    utilisateur_id  BIGINT NOT NULL CONSTRAINT fk_participant_utilisateur REFERENCES utilisateur (id),
    PRIMARY KEY (sortie_id, utilisateur_id)
);

-- Liste d'attente : "position" garde l'ordre d'arrivée (0, 1, 2… : @OrderColumn)
CREATE TABLE sortie_attente (
    sortie_id       BIGINT  NOT NULL CONSTRAINT fk_attente_sortie REFERENCES sortie (id),
    utilisateur_id  BIGINT  NOT NULL CONSTRAINT fk_attente_utilisateur REFERENCES utilisateur (id),
    "position"      INTEGER NOT NULL CONSTRAINT ck_attente_position CHECK ("position" >= 0),
    PRIMARY KEY (sortie_id, "position")
);

CREATE TABLE photo_sortie (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    url         VARCHAR(255),                   -- /api/fichiers/albums/… (photo ou vidéo)
    date_ajout  TIMESTAMP(6) WITHOUT TIME ZONE,
    auteur_id   BIGINT CONSTRAINT fk_photo_auteur REFERENCES utilisateur (id),
    sortie_id   BIGINT CONSTRAINT fk_photo_sortie REFERENCES sortie (id)
);

-- ---------- Commentaires et avis (un avis = un commentaire avec une note) ----------
CREATE TABLE commentaire (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contenu        VARCHAR(255) NOT NULL,
    note           INTEGER CONSTRAINT ck_commentaire_note CHECK (note >= 1 AND note <= 5),
    cible_type     VARCHAR(255) NOT NULL,       -- "sortie", "point", "activite"
    cible_id       BIGINT,
    date_creation  TIMESTAMP(6) WITHOUT TIME ZONE,
    auteur_id      BIGINT CONSTRAINT fk_commentaire_auteur REFERENCES utilisateur (id)
);

-- ---------- Social ----------
CREATE TABLE message (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contenu          VARCHAR(2000),
    lu               BOOLEAN NOT NULL,
    date_envoi       TIMESTAMP(6) WITHOUT TIME ZONE,
    expediteur_id    BIGINT CONSTRAINT fk_message_expediteur REFERENCES utilisateur (id),
    destinataire_id  BIGINT CONSTRAINT fk_message_destinataire REFERENCES utilisateur (id)
);

CREATE TABLE notification (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type             VARCHAR(255),
    texte            VARCHAR(255),
    lien             VARCHAR(255),
    lue              BOOLEAN NOT NULL,
    date_creation    TIMESTAMP(6) WITHOUT TIME ZONE,
    destinataire_id  BIGINT CONSTRAINT fk_notification_destinataire REFERENCES utilisateur (id)
);

CREATE TABLE favori (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cible_type      VARCHAR(255),               -- "point", "activite" ou "sortie"
    cible_id        BIGINT,
    date_ajout      TIMESTAMP(6) WITHOUT TIME ZONE,
    utilisateur_id  BIGINT CONSTRAINT fk_favori_utilisateur REFERENCES utilisateur (id),
    CONSTRAINT uk_favori UNIQUE (utilisateur_id, cible_type, cible_id)
);

CREATE TABLE abonnement (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date_abonnement  TIMESTAMP(6) WITHOUT TIME ZONE,
    abonne_id        BIGINT CONSTRAINT fk_abonnement_abonne REFERENCES utilisateur (id),   -- celui qui suit
    suivi_id         BIGINT CONSTRAINT fk_abonnement_suivi REFERENCES utilisateur (id),    -- celui qui est suivi
    CONSTRAINT uk_abonnement UNIQUE (abonne_id, suivi_id)
);

CREATE TABLE blocage (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date_blocage  TIMESTAMP(6) WITHOUT TIME ZONE,
    bloqueur_id   BIGINT CONSTRAINT fk_blocage_bloqueur REFERENCES utilisateur (id),
    bloque_id     BIGINT CONSTRAINT fk_blocage_bloque REFERENCES utilisateur (id),
    CONSTRAINT uk_blocage UNIQUE (bloqueur_id, bloque_id)
);

CREATE TABLE signalement (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cible_type     VARCHAR(255),                -- "membre", "sortie", "commentaire" ou "photo"
    cible_id       BIGINT,
    motif          VARCHAR(500),
    traite         BOOLEAN NOT NULL,
    date_creation  TIMESTAMP(6) WITHOUT TIME ZONE,
    auteur_id      BIGINT CONSTRAINT fk_signalement_auteur REFERENCES utilisateur (id)
);
