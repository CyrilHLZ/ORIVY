-- V20 : suggestions des membres (bouton « Suggérer » de la carte) :
--   type 'lieu' : demande d'ajout d'un lieu précis (nom, catégorie, adresse) ;
--   type 'idee' : une idée pour ORIVY.
-- L'admin les lit dans sa page et les marque « traitées ». Compte supprimé : la suggestion reste, sans auteur.
CREATE TABLE suggestion (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type           VARCHAR(10)  NOT NULL,
    nom_lieu       VARCHAR(255),
    categorie      VARCHAR(50),
    adresse        VARCHAR(255),
    latitude       DOUBLE PRECISION,
    longitude      DOUBLE PRECISION,
    message        VARCHAR(1000),
    traite         BOOLEAN      NOT NULL DEFAULT FALSE,
    date_creation  TIMESTAMP(6) WITHOUT TIME ZONE,
    auteur_id      BIGINT CONSTRAINT fk_suggestion_auteur REFERENCES utilisateur (id) ON DELETE SET NULL
);
CREATE INDEX idx_suggestion_traite ON suggestion (traite, date_creation);
